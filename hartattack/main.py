# This script executes the fuzzer on a given design to find faulting programs.

from hartattack import *
from hartattack import runparams
import os
import sys
import argparse

# First version with ordered dictionaries
MIN_VERSION = (3, 7, 0)


def parse_bool(val):
    return str(val).lower() in ("1", "true", "yes")


def add_parsing_rules():
    parser = argparse.ArgumentParser(
        description="Run the Cascade fuzzer on a design to find faulting programs."
    )
    parser.add_argument("design_name", help="Design name")
    parser.add_argument(
        "--num-cores", type=int, default=1, help="Number of cores allocated to fuzzing"
    )
    parser.add_argument(
        "--memsize", type=int, default=None, help="Size of the memory in bytes"
    )
    parser.add_argument(
        "--num-bbs", type=int, default=None, help="maximla number of basic blocks"
    )
    parser.add_argument(
        "--reduce",
        type=int,
        metavar="SEED",
        help="Reduces the program generated by the given SEED (*experimental*)",
    )
    parser.add_argument(
        "--gensingle",
        type=int,
        metavar="SEED",
        help="Generates a specific elf, given its random seed",
    )
    parser.add_argument(
        "--fuzzsingle",
        type=int,
        metavar="SEED",
        help="Fuzzes a single elf, given its random seed",
    )
    parser.add_argument(
        "--manyelfs",
        type=int,
        metavar="NUM_ELFS",
        help="Generates NUM_ELFS testcase",
    )
    parser.add_argument("--seed-offset", type=int, default=0, help="Offset for seed")
    parser.add_argument(
        "--authorize-privileges",
        type=parse_bool,
        default=True,
        help="Authorize privileges (default: True)",
    )
    parser.add_argument(
        "--tolerate-some-bug",
        type=int,
        default=0,
        help="Tolerate some bug (default: 0)",
    )
    parser.add_argument(
        "--keep-tmpfiles",
        action="store_true",
        help="Keep temporary files after execution",
    )
    parser.add_argument(
        "--debug-rtl",
        action="store_true",
        help="Generate an ELF but with spike device addresses",
    )
    parser.add_argument(
        "--fuzz-mcm",
        action="store_true",
        help="Fuzz the Memory Consistency Model",
    )
    parser.add_argument(
        "--use-addr-regs",
        type=parse_bool,
        default=True,
        help="use addr regs, not using addr regs might break the program (default: True)",
    )
    parser.add_argument(
        "--no-final-check",
        action="store_true",
        help="Will not manually check the registers after execution",
    )
    parser.add_argument(
        "--fuzz-interrupts",
        action="store_true",
        help="Enables fuzzing interrupts",
    )
    parser.add_argument(
        "--verify-memory-trace",
        type=str,
        default=None,
        help="Verifies the memory trace instead of enumerating solutions. Must specify backend: herd or dat",
    )
    parser.add_argument(
        "--skip-no-interrupts",
        action="store_true",
        help="Skips testcase with no interrupts",
    )
    parser.add_argument(
        "--jit-scenario",
        action="store_true",
        help="enables jit scenario",
    )
    parser.add_argument(
        "--stress-core",
        action="store_true",
        help="Enables stress core generation",
    )
    parser.add_argument(
        "--max-n-consecutive-memops",
        type=int,
        default=5,
        help="Maximum number of consecutive memory operations per basic block (default: 5)",
    )
    return parser


def main():
    parser = add_parsing_rules()
    args = parser.parse_args()

    designs_proc_dir = os.getenv("HARTATTACK_SIMULATORS_DIR")
    if not designs_proc_dir:
        raise EnvironmentError("HARTATTACK_SIMULATORS_DIR not set")
    available_designs = [
        name
        for name in os.listdir(designs_proc_dir)
        if os.path.isdir(os.path.join(designs_proc_dir, name))
    ]
    if args.design_name not in available_designs:
        print(
            f"Error: design_name '{args.design_name}' is not a valid directory in {designs_proc_dir}."
        )
        print("Available designs:\n    -", "\n    - ".join(available_designs))
        sys.exit(1)

    runparams.FUZZ_MCM = args.fuzz_mcm
    if args.use_addr_regs and not runparams.FUZZ_MCM:
        runparams.USE_ADDR_REGS = False
    else:
        runparams.USE_ADDR_REGS = args.use_addr_regs

    runparams.REMOVE_TMPFILES = not args.keep_tmpfiles
    runparams.DEBUG_RTL = args.debug_rtl
    runparams.NO_FINAL_CHECK = args.no_final_check
    runparams.FUZZ_INTERRUPT = args.fuzz_interrupts
    runparams.VERIFY_MEMORY_TRACE = args.verify_memory_trace
    runparams.SKIP_NO_INTERRUPT = args.skip_no_interrupts
    runparams.JIT_SCENARIO = args.jit_scenario
    runparams.FUZZ_STRESS_CORE = args.stress_core
    runparams.MAX_N_CONSECUTIVE_MEMOPS = args.max_n_consecutive_memops

    if args.tolerate_some_bug:
        tolerate_bug_for_eval_reduction(args.design_name)

    if args.reduce is not None:
        reducer = ReduceProgram(args.design_name, args.reduce, True)
        reducer.reduce_testcase()
        print("needs fixing with imports")
        sys.exit(1)

    if args.gensingle is not None:
        seed_offset = args.gensingle
    elif args.fuzzsingle is not None:
        seed_offset = args.fuzzsingle
    else:
        seed_offset = args.seed_offset

    fuzz_design = FuzzDesign(
        args.design_name,
        args.num_cores,
        seed_offset,
        args.authorize_privileges,
        args.memsize,
        args.num_bbs,
    )

    if args.gensingle is not None:
        fuzz_design.gen_specific_elf()
    elif args.fuzzsingle is not None:
        fuzz_design.fuzz_single()
    elif args.manyelfs is not None:
        fuzz_design.gen_many_elfs(args.manyelfs)
    else:
        fuzz_design.start()


if __name__ == "__main__":
    if sys.version_info < MIN_VERSION:
        raise EnvironmentError(
            "Python {}+ required for ordered dictionaries".format(
                ".".join(str(n) for n in MIN_VERSION)
            )
        )
    # TODO we could manually source it here
    if "HARTATTACK_ENV_SOURCED" not in os.environ:
        raise Exception(
            "The Cascade environment must be sourced prior to running the Python recipes."
        )
    main()
