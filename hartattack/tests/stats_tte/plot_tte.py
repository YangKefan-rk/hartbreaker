#!/usr/bin/env python3
"""
Plot time-to-exposure (TTE) data generated by main.py.
Reads JSONL files from /scratch/bordierq/tte_data/<design>/ and produces
a CDF plot of bug rediscovery times per design.
"""

import json
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path
import sys

SMALL_SIZE = 8
MEDIUM_SIZE = 9
BIGGER_SIZE = 10

plt.rc("font", size=SMALL_SIZE)
plt.rc("axes", titlesize=BIGGER_SIZE)
plt.rc("axes", labelsize=MEDIUM_SIZE)
plt.rc("xtick", labelsize=SMALL_SIZE)
plt.rc("ytick", labelsize=SMALL_SIZE)
plt.rc("legend", fontsize=SMALL_SIZE)
plt.rc("figure", titlesize=BIGGER_SIZE)

colors_c = ["#0D75FF"]

DESIGN_LABELS = {
    "naxriscv_mcm": "N1",
    "naxriscv": "N1", # legacy
    "naxriscv_int": "N2",
    "dualboomv4": "B1",
    "toooba": "T1",
    "xiangshan": "X1",
}

def load_tte_data(file_path: Path) -> list[float]:
    """Load TTE values (in seconds) from a JSONL file."""
    times = []
    with open(file_path, "r") as f:
        for line in f:
            if line.strip():
                data = json.loads(line)
                times.append(data["time_s"])
    return times


MARKERS = ["o", "s", "^", "D", "v"]


def plot_tte(base_dir: Path, output_dir: Path):
    """Create a box plot of time-to-exposure per design."""
    # Discover designs
    design_dirs = sorted([d for d in base_dir.iterdir() if d.is_dir()])

    labels = []
    all_times = []
    box_colors = []

    for i, design_dir in enumerate(design_dirs):
        jsonl_files = list(design_dir.glob("*.jsonl"))
        if not jsonl_files:
            continue

        times_s = load_tte_data(jsonl_files[0])
        if not times_s:
            continue

        times_h = np.array(times_s) / 3600.0
        labels.append(DESIGN_LABELS.get(design_dir.name, design_dir.name))
        all_times.append(times_h)
        box_colors.append(colors_c[i % len(colors_c)])

    fig, ax = plt.subplots(figsize=(3.5, 2))

    bp = ax.boxplot(all_times, patch_artist=True, widths=0.5, showfliers=False)
    for patch, color in zip(bp["boxes"], box_colors):
        patch.set_facecolor(color)
        patch.set_alpha(0.7)
    for median in bp["medians"]:
        median.set_color("black")

    ax.set_xticks(range(1, len(labels) + 1))
    ax.set_xticklabels(labels, rotation=0)
    ax.set_ylabel("Time to Exposure\n(core-hours)")
    ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    output_file = output_dir / "tte_avg"
    plt.savefig(f"{output_file}.pdf", format="pdf", bbox_inches="tight")
    print(f"Plot saved to {output_file}.pdf")


def main():
    if len(sys.argv) < 2:
        base_dir = Path("/scratch/bordierq/tte_data")
    else:
        base_dir = Path(sys.argv[1])

    if not base_dir.exists():
        print(f"Error: Directory {base_dir} does not exist")
        sys.exit(1)

    output_dir = Path(__file__).parent
    plot_tte(base_dir, output_dir)


if __name__ == "__main__":
    main()
